#ifndef DCM_CFG_H_
#define DCM_CFG_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/

#include "Std_Types.h"
#include "ComStack_Types.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_RX_BUFFER_SIZE                          (2048U)
#define DCM_TX_BUFFER_SIZE                          (2048U)
#define DCM_LENGTH_FORMAT_MAX_BLOCK_LENGTH          (0x30U)
/*********************************************************************************************************************/
/*---------------------------------------------------DCM PDU IDs-----------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * Target ECU 기준 DCM Rx PDU
 *
 * Gateway → CanTp → PduR → Dcm
 */
#define DCM_RXPDU_DIAG_REQ                         (0U)
#define DCM_RXPDU_COUNT                            (1U)

/*
 * Target ECU 기준 DCM Tx PDU
 *
 * Dcm → PduR → CanTp → Gateway
 */
#define DCM_TXPDU_DIAG_RES                         (0U)
#define DCM_TXPDU_COUNT                            (1U)

/*********************************************************************************************************************/
/*---------------------------------------------------UDS Service IDs-------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_SID_DIAGNOSTIC_SESSION_CONTROL         (0x10U)
#define DCM_SID_ECU_RESET                          (0x11U)
#define DCM_SID_READ_DATA_BY_IDENTIFIER            (0x22U)
#define DCM_SID_TESTER_PRESENT                     (0x3EU)

#define DCM_SID_REQUEST_DOWNLOAD                   (0x34U)
#define DCM_SID_TRANSFER_DATA                      (0x36U)
#define DCM_SID_REQUEST_TRANSFER_EXIT              (0x37U)

#define DCM_SID_ROUTINE_CONTROL                    (0x31U)

/*********************************************************************************************************************/
/*------------------------------------------------Data Identifiers---------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * FOTA Status DID
 *
 * Request:
 *   22 F1 80
 *
 * Positive Response:
 *   62 F1 80 [FotaState] [LastFotaResult]
 */
#define DCM_DID_FOTA_STATUS                         (0xF180U)

/*********************************************************************************************************************/
/*------------------------------------------------Positive Response--------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_POSITIVE_RESPONSE_OFFSET               (0x40U)

/*********************************************************************************************************************/
/*------------------------------------------------Negative Response--------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_NEGATIVE_RESPONSE_SID                  (0x7FU)

#define DCM_NRC_GENERAL_REJECT                     (0x10U)
#define DCM_NRC_SERVICE_NOT_SUPPORTED              (0x11U)
#define DCM_NRC_SUBFUNCTION_NOT_SUPPORTED          (0x12U)
#define DCM_NRC_INCORRECT_MESSAGE_LENGTH           (0x13U)
#define DCM_NRC_CONDITIONS_NOT_CORRECT             (0x22U)
#define DCM_NRC_REQUEST_SEQUENCE_ERROR             (0x24U)
#define DCM_NRC_REQUEST_OUT_OF_RANGE               (0x31U)
#define DCM_NRC_TRANSFER_DATA_SUSPENDED            (0x71U)
#define DCM_NRC_GENERAL_PROGRAMMING_FAILURE        (0x72U)

/*********************************************************************************************************************/
/*------------------------------------------------Session Values-----------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_SESSION_VALUE_DEFAULT                  (0x01U)
#define DCM_SESSION_VALUE_PROGRAMMING              (0x02U)
#define DCM_SESSION_VALUE_EXTENDED                 (0x03U)

/*********************************************************************************************************************/
/*------------------------------------------------ECU Reset Values---------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_RESET_HARD_RESET                       (0x01U)

/*********************************************************************************************************************/
/*------------------------------------------------Routine IDs--------------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * 임시 FOTA Routine ID
 *
 * 실제 표준 RID/사내 RID를 쓰는 것이 아니라,
 * 프로젝트 테스트용으로 임의 정의한 값이다.
 */
#define DCM_RID_VERIFY_IMAGE                       (0xFF01U)
#define DCM_RID_ACTIVATE_IMAGE                     (0xFF02U)
#define DCM_RID_ROLLBACK_IMAGE                     (0xFF03U)

#define DCM_ROUTINE_CONTROL_START_ROUTINE          (0x01U)
#define DCM_ROUTINE_CONTROL_STOP_ROUTINE           (0x02U)
#define DCM_ROUTINE_CONTROL_REQUEST_RESULT         (0x03U)

/*********************************************************************************************************************/
/*------------------------------------------------Download Config----------------------------------------------------*/
/*********************************************************************************************************************/

#define DCM_MAX_BLOCK_SEQUENCE_COUNTER             (0xFFU)

#define DCM_MAX_TRANSFER_BLOCK_LENGTH              (1026U)

#endif /* DCM_CFG_H_ */
