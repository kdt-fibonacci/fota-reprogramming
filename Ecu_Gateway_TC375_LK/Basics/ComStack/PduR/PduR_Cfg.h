#ifndef PDUR_CFG_H_
#define PDUR_CFG_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/

#include "PduR.h"
#include "ComStack_Types.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Counts-------------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * 1. DoIP -> CanTp
 *    Tester의 UDS Request를 CAN ECU0/ECU1로 전달
 *
 * 2. CanTp -> DoIP
 *    CAN ECU0/ECU1의 UDS Response를 Tester에게 전달
 */
#define PDUR_ROUTING_PATH_COUNT                         (4U)

/*********************************************************************************************************************/
/*--------------------------------------------------Routing Path IDs-------------------------------------------------*/
/*********************************************************************************************************************/

#define PDUR_ROUTE_DOIP_TO_CANTP_TESTER_TO_ECU0         (0U)
#define PDUR_ROUTE_DOIP_TO_CANTP_TESTER_TO_ECU1         (1U)
#define PDUR_ROUTE_CANTP_TO_DOIP_ECU0_TO_TESTER         (2U)
#define PDUR_ROUTE_CANTP_TO_DOIP_ECU1_TO_TESTER         (3U)

/*********************************************************************************************************************/
/*------------------------------------------------PduR-facing PDU IDs-----------------------------------------------*/
/*********************************************************************************************************************/

#define PDUR_RXPDU_CANTP_ECU0_TO_TESTER                 (0U)
#define PDUR_RXPDU_CANTP_ECU1_TO_TESTER                 (1U)

#define PDUR_TXCONF_CANTP_TESTER_TO_ECU0                (0U)
#define PDUR_TXCONF_CANTP_TESTER_TO_ECU1                (1U)

/*********************************************************************************************************************/
/*------------------------------------------------------Types--------------------------------------------------------*/
/*********************************************************************************************************************/

typedef enum
{
    PDUR_MODULE_DCM = 0U,
    PDUR_MODULE_CANTP,
    PDUR_MODULE_DOIPTP
} PduR_ModuleType;

typedef enum
{
    PDUR_EVENT_TRANSMIT = 0U,
    PDUR_EVENT_RX_INDICATION,
    PDUR_EVENT_TX_CONFIRMATION
} PduR_EventType;

typedef struct
{
    PduIdType       PduRRoutingPathId;

    PduR_ModuleType SourceModule;
    PduIdType       SourcePduId;

    PduR_ModuleType DestModule;
    PduIdType       DestPduId;

    PduR_EventType  RoutingEvent;
} PduR_RoutingPathConfigType;

/*********************************************************************************************************************/
/*---------------------------------------------------Extern Configs--------------------------------------------------*/
/*********************************************************************************************************************/

extern const PduR_RoutingPathConfigType
    PduR_RoutingPathConfig[PDUR_ROUTING_PATH_COUNT];

#endif /* PDUR_CFG_H_ */
