#ifndef CANIF_CFG_H_
#define CANIF_CFG_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/

#include "CanIf.h"
#include "Can_Cfg.h"
#include "CanTp_Cfg.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Counts-------------------------------------------------------*/
/*********************************************************************************************************************/

#define CANIF_TXPDU_COUNT                 (2U)
#define CANIF_RXPDU_COUNT                 (2U)

/*********************************************************************************************************************/
/*--------------------------------------------------Tx L-PDU IDs-----------------------------------------------------*/
/*********************************************************************************************************************/

#define CANIF_TXPDU_GATEWAY_TO_ECU0       (0U)
#define CANIF_TXPDU_GATEWAY_TO_ECU1       (1U)

/*********************************************************************************************************************/
/*--------------------------------------------------Rx L-PDU IDs-----------------------------------------------------*/
/*********************************************************************************************************************/

#define CANIF_RXPDU_ECU0_TO_GATEWAY       (0U)
#define CANIF_RXPDU_ECU1_TO_GATEWAY       (1U)

/*********************************************************************************************************************/
/*------------------------------------------------------Types--------------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * CanIf_TxPduConfigType
 *
 * CanIf 기준 Tx L-PDU 설정이다.
 *
 * CanIfTxPduId:
 *   상위 계층(CanTp)이 CanIf_Transmit()을 호출할 때 사용하는
 *   CanIf 기준 송신 L-PDU handle.
 *
 * CanId:
 *   실제 CAN bus에 송신될 CAN ID.
 *
 * Hth:
 *   Can Driver의 Hardware Transmit Handle.
 *   Can_Write(Hth, PduInfoPtr)에 사용된다.
 *
 * CanTpTxPduId:
 *   Can Driver의 Tx 완료 알림을 CanTp로 전달할 때 사용하는
 *   CanTp 기준 Tx PDU handle.
 */
typedef struct
{
    PduIdType        CanIfTxPduId;
    Can_IdType       CanId;
    Can_HwHandleType Hth;
    PduIdType        CanTpTxPduId;
} CanIf_TxPduConfigType;


/*
 * CanIf_RxPduConfigType
 *
 * CanIf 기준 Rx L-PDU 설정이다.
 *
 * CanIfRxPduId:
 *   CanIf 내부에서 수신 L-PDU를 식별하는 handle.
 *
 * Hrh:
 *   Can Driver가 알려주는 수신 Hardware Receive Handle.
 *
 * CanId:
 *   수신 CAN ID.
 *
 * CanTpRxPduId:
 *   CanIf가 수신 L-PDU를 CanTp로 전달할 때 사용하는
 *   CanTp 기준 Rx PDU handle.
 */
typedef struct
{
    PduIdType        CanIfRxPduId;
    Can_HwHandleType Hrh;
    Can_IdType       CanId;
    PduIdType        CanTpRxPduId;
} CanIf_RxPduConfigType;

/*********************************************************************************************************************/
/*---------------------------------------------------Extern Configs--------------------------------------------------*/
/*********************************************************************************************************************/

extern const CanIf_TxPduConfigType CanIf_TxPduConfig[CANIF_TXPDU_COUNT];
extern const CanIf_RxPduConfigType CanIf_RxPduConfig[CANIF_RXPDU_COUNT];

#endif /* CANIF_CFG_H_ */
