#ifndef PDUR_CFG_H_
#define PDUR_CFG_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/

#include "PduR.h"
#include "ComStack_Types.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Counts-------------------------------------------------------*/
/*********************************************************************************************************************/

#define PDUR_ROUTING_PATH_COUNT                         (3U)

/*********************************************************************************************************************/
/*--------------------------------------------------Routing Path IDs-------------------------------------------------*/
/*********************************************************************************************************************/

/*
 * Target ECU 기준 routing path
 *
 * 1. Gateway에서 들어온 UDS Request를 Dcm으로 전달
 * 2. Dcm의 UDS Response를 CanTp로 전달
 * 3. CanTp 송신 완료를 Dcm에 통지
 */
#define PDUR_ROUTE_CANTP_TO_DCM_REMOTE_TO_LOCAL         (0U)
#define PDUR_ROUTE_DCM_TO_CANTP_LOCAL_TO_REMOTE         (1U)
#define PDUR_ROUTE_CANTP_TXCONF_TO_DCM_LOCAL_TO_REMOTE  (2U)

/*********************************************************************************************************************/
/*------------------------------------------------------Types--------------------------------------------------------*/
/*********************************************************************************************************************/

typedef enum
{
    PDUR_MODULE_DCM = 0U,
    PDUR_MODULE_CANTP,
    PDUR_MODULE_DOIPTP
} PduR_ModuleType;

typedef enum
{
    PDUR_EVENT_TRANSMIT = 0U,
    PDUR_EVENT_RX_INDICATION,
    PDUR_EVENT_TX_CONFIRMATION
} PduR_EventType;

typedef struct
{
    PduIdType       PduRRoutingPathId;

    PduR_ModuleType SourceModule;
    PduIdType       SourcePduId;

    PduR_ModuleType DestModule;
    PduIdType       DestPduId;

    PduR_EventType  RoutingEvent;
} PduR_RoutingPathConfigType;

/*********************************************************************************************************************/
/*---------------------------------------------------Extern Configs--------------------------------------------------*/
/*********************************************************************************************************************/

extern const PduR_RoutingPathConfigType
    PduR_RoutingPathConfig[PDUR_ROUTING_PATH_COUNT];

#endif /* PDUR_CFG_H_ */