/*********************************************************************************************************************/
/*------------------------------------------------Main Function------------------------------------------------------*/
/*********************************************************************************************************************/

void core0_main(void)
{
    IfxCpu_enableInterrupts();

    IfxScuWdt_disableCpuWatchdog(
        IfxScuWdt_getCpuWatchdogPassword()
    );

    IfxScuWdt_disableSafetyWatchdog(
        IfxScuWdt_getSafetyWatchdogPassword()
    );

    Test_InitModules();
    App_Scheduler_Init();

    UART_Printf("\r\n");
    UART_Printf("[Motion ECU] Current Version: A\r\n");
    UART_Printf("========================================\r\n");
    UART_Printf("[Motion] Target DCM Responder Start\r\n");
    UART_Printf("========================================\r\n");

    while (1)
    {
        App_Scheduler_Run();
    }
}

/*********************************************************************************************************************/
/*------------------------------------------------Module Init/Main---------------------------------------------------*/
/*********************************************************************************************************************/

static void Test_InitModules(void)
{
    UART_Init();
    Can_Init();

    (void)Can_SetControllerMode(
    CAN_CONTROLLER_0,
    CAN_CS_STARTED
    );

    CanIf_Init();
    CanTp_Init();
    PduR_Init();
    Dcm_Init();
    FOTA_ProvisionInitialOnce();
}
